export interface CatalogItemTemplate {
  id: string;
  category: FurnitureCategory;
  subType: 'base' | 'wall' | 'tall' | 'corner' | 'top' | 'backsplash' | 'wardrobe_sliding' | 'wardrobe_swing';
  mainGroup: CatalogMainGroup;
  subGroup: CatalogSubGroup;
  code?: string; // Русское унифицированное обозначение секции (НС-2Д, ВС-2С, П-Д-СВЧ-ДШ-2В и др.)
  name: string;
  description: string;
  defaultDimensions: {
    width: number;
    height: number;
    depth: number;
  };
  allowedDimensions?: {
    minWidth: number;
    maxWidth: number;
    minHeight: number;
    maxHeight: number;
    minDepth: number;
    maxDepth: number;
  };
  standardWidths?: number[];
  tags?: string[];
  defaultConfig: ModuleConfig;
  basePrice: number;
}


export function getModuleCode(item?: { code?: string; id?: string; catalogId?: string; name?: string } | null): string {
  if (!item) return '';
  if (item.code) return item.code;
  const targetId = item.catalogId || item.id;
  if (targetId) {
    const tpl = CATALOG_ITEMS.find((c) => c.id === targetId);
    if (tpl?.code) return tpl.code;
  }
  if (item.name) {
    const match = item.name.match(/^([А-ЯЁ0-9-]+)/);
    if (match && (match[1].startsWith('НС-') || match[1].startsWith('ВС-') || match[1].startsWith('П-') || match[1].startsWith('ФАРТУК-'))) {
      return match[1];
    }
  }
  return '';
}

